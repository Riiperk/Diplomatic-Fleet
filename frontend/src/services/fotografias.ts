const porUrl = new Map(fotografias.map(f => [f.url, f]))
/** Consulta de atribución por URL exacta; no asigna ni cambia imágenes. */
export function creditoFoto(url: string | null | undefined): CreditoFoto | undefined {
  return url ? porUrl.get(url) : undefined
}
/** Admite HTTPS y recursos locales; evita URLs de páginas, datos y esquemas ejecutables. */
export function urlFoto(url: string | null | undefined): string {
  const valor = url?.trim() ?? ''
  if (/^\/assets\/images\/[a-zA-Z0-9_./-]+$/.test(valor) && !valor.includes('..')) return valor
  try { const u = new URL(valor); return u.protocol === 'https:' && !u.username && !u.password ? u.href : '' } catch { return '' }
}
