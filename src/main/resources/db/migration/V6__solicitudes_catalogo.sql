-- Solicitudes preliminares desde el catálogo público.
-- No equivalen a reservas confirmadas ni afectan la disponibilidad operativa.
-- Este proceso convive con el flujo institucional completo de solicitudes (V3).
CREATE TABLE solicitudes_catalogo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehiculo_id BIGINT NOT NULL REFERENCES vehiculos(id) ON DELETE RESTRICT,
    nombre_contacto VARCHAR(120) NOT NULL,
    correo_contacto VARCHAR(150) NOT NULL,
    entidad VARCHAR(150) NOT NULL,
    telefono VARCHAR(30),
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    mensaje VARCHAR(600),
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    consentimiento_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_solicitudes_catalogo_fechas CHECK (fecha_fin >= fecha_inicio),
    CONSTRAINT chk_solicitudes_catalogo_estado
        CHECK (estado IN ('PENDIENTE', 'CONTACTADA', 'CERRADA', 'CANCELADA')),
    CONSTRAINT chk_solicitudes_catalogo_contacto CHECK (
        TRIM(nombre_contacto) <> '' AND TRIM(correo_contacto) <> '' AND TRIM(entidad) <> ''
    )
);

CREATE INDEX idx_solicitudes_catalogo_estado_fecha
    ON solicitudes_catalogo(estado, creado_en DESC);
CREATE INDEX idx_solicitudes_catalogo_vehiculo
    ON solicitudes_catalogo(vehiculo_id);

COMMENT ON TABLE solicitudes_catalogo IS 'Intereses de alquiler recibidos por web; requieren verificación institucional y confirmación humana.';
