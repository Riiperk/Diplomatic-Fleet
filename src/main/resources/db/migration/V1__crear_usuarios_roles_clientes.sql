-- ============================================================
-- Diplomatic Fleet
-- Migración V1: usuarios, roles y clientes institucionales
--
-- Esta migración crea las estructuras necesarias para:
-- 1. Administrar las cuentas de acceso.
-- 2. Asignar uno o varios roles a cada usuario.
-- 3. Registrar embajadas, consulados y otras organizaciones.
--
-- Flyway ejecuta este archivo una sola vez y registra el
-- resultado en la tabla flyway_schema_history.
-- ============================================================


-- ============================================================
-- TABLA: roles
-- ============================================================

CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nombre VARCHAR(50) NOT NULL,

    descripcion VARCHAR(255),

    activo BOOLEAN NOT NULL DEFAULT TRUE,

    creado_en TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_roles_nombre
        UNIQUE (nombre),

    CONSTRAINT chk_roles_nombre_no_vacio
        CHECK (TRIM(nombre) <> '')
);

COMMENT ON TABLE roles IS
    'Catálogo de roles utilizados para controlar los permisos del sistema.';

COMMENT ON COLUMN roles.nombre IS
    'Nombre único del rol, por ejemplo ADMINISTRADOR u OPERACIONES.';

COMMENT ON COLUMN roles.activo IS
    'Indica si el rol está disponible para nuevas asignaciones.';


-- ============================================================
-- TABLA: usuarios
-- ============================================================

CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nombre VARCHAR(70) NOT NULL,

    apellido VARCHAR(70) NOT NULL,

    correo VARCHAR(150) NOT NULL,

    password_hash VARCHAR(255) NOT NULL,

    telefono VARCHAR(30),

    activo BOOLEAN NOT NULL DEFAULT TRUE,

    creado_en TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    actualizado_en TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_usuarios_nombre_no_vacio
        CHECK (TRIM(nombre) <> ''),

    CONSTRAINT chk_usuarios_apellido_no_vacio
        CHECK (TRIM(apellido) <> ''),

    CONSTRAINT chk_usuarios_correo_no_vacio
        CHECK (TRIM(correo) <> ''),

    CONSTRAINT chk_usuarios_password_hash_no_vacio
        CHECK (TRIM(password_hash) <> '')
);

-- Este índice evita correos duplicados sin distinguir mayúsculas.
-- Por ejemplo, ADMIN@CORREO.COM y admin@correo.com se consideran iguales.
CREATE UNIQUE INDEX uq_usuarios_correo_normalizado
    ON usuarios (LOWER(TRIM(correo)));

COMMENT ON TABLE usuarios IS
    'Cuentas autorizadas para acceder a Diplomatic Fleet.';

COMMENT ON COLUMN usuarios.correo IS
    'Correo utilizado como identificador de acceso.';

COMMENT ON COLUMN usuarios.password_hash IS
    'Contraseña codificada. Nunca debe almacenarse la contraseña en texto plano.';

COMMENT ON COLUMN usuarios.activo IS
    'Permite desactivar una cuenta sin eliminar su historial.';


-- ============================================================
-- TABLA INTERMEDIA: usuarios_roles
-- ============================================================

CREATE TABLE usuarios_roles (
    usuario_id BIGINT NOT NULL,

    rol_id BIGINT NOT NULL,

    asignado_en TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_usuarios_roles
        PRIMARY KEY (usuario_id, rol_id),

    CONSTRAINT fk_usuarios_roles_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES usuarios (id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_usuarios_roles_rol
        FOREIGN KEY (rol_id)
        REFERENCES roles (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

COMMENT ON TABLE usuarios_roles IS
    'Tabla asociativa que implementa la relación muchos a muchos entre usuarios y roles.';

COMMENT ON COLUMN usuarios_roles.asignado_en IS
    'Fecha y hora en la que el rol fue asignado al usuario.';


-- ============================================================
-- TABLA: clientes_institucionales
-- ============================================================

CREATE TABLE clientes_institucionales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nombre_entidad VARCHAR(150) NOT NULL,

    tipo_entidad VARCHAR(40) NOT NULL,

    numero_identificacion_fiscal VARCHAR(40),

    nombre_contacto VARCHAR(140) NOT NULL,

    correo_contacto VARCHAR(150) NOT NULL,

    telefono_contacto VARCHAR(30),

    direccion VARCHAR(255),

    ciudad VARCHAR(100),

    activo BOOLEAN NOT NULL DEFAULT TRUE,

    creado_en TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    actualizado_en TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_clientes_nombre_entidad_no_vacio
        CHECK (TRIM(nombre_entidad) <> ''),

    CONSTRAINT chk_clientes_nombre_contacto_no_vacio
        CHECK (TRIM(nombre_contacto) <> ''),

    CONSTRAINT chk_clientes_correo_contacto_no_vacio
        CHECK (TRIM(correo_contacto) <> ''),

    CONSTRAINT chk_clientes_tipo_entidad
        CHECK (
            tipo_entidad IN (
                'EMBAJADA',
                'CONSULADO',
                'ORGANISMO_INTERNACIONAL',
                'OTRO'
            )
        )
);

CREATE UNIQUE INDEX uq_clientes_nombre_entidad_normalizado
    ON clientes_institucionales (
        LOWER(TRIM(nombre_entidad))
    );

CREATE UNIQUE INDEX uq_clientes_correo_contacto_normalizado
    ON clientes_institucionales (
        LOWER(TRIM(correo_contacto))
    );

CREATE UNIQUE INDEX uq_clientes_identificacion_fiscal
    ON clientes_institucionales (
        numero_identificacion_fiscal
    )
    WHERE numero_identificacion_fiscal IS NOT NULL;

COMMENT ON TABLE clientes_institucionales IS
    'Embajadas, consulados y organizaciones que solicitan servicios vehiculares.';

COMMENT ON COLUMN clientes_institucionales.tipo_entidad IS
    'Clasificación institucional: EMBAJADA, CONSULADO, ORGANISMO_INTERNACIONAL u OTRO.';

COMMENT ON COLUMN clientes_institucionales.nombre_contacto IS
    'Persona responsable de la comunicación con la entidad institucional.';

COMMENT ON COLUMN clientes_institucionales.numero_identificacion_fiscal IS
    'Identificación tributaria o institucional cuando corresponda.';

COMMENT ON COLUMN clientes_institucionales.activo IS
    'Permite inactivar una entidad sin eliminar solicitudes históricas.';


-- ============================================================
-- ÍNDICES PARA CONSULTAS FRECUENTES
-- ============================================================

CREATE INDEX idx_usuarios_activo
    ON usuarios (activo);

CREATE INDEX idx_clientes_institucionales_tipo
    ON clientes_institucionales (tipo_entidad);

CREATE INDEX idx_clientes_institucionales_activo
    ON clientes_institucionales (activo);