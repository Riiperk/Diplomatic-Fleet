-- V9: ampliacion no destructiva del ciclo de reserva.
-- Conserva las solicitudes existentes y no modifica las migraciones V1-V8.
-- El pago es manual/externo: esta tabla NO ejecuta cobros ni guarda datos de tarjeta.

ALTER TABLE solicitudes
    ADD COLUMN fecha_inicio_real TIMESTAMP WITH TIME ZONE,
    ADD COLUMN fecha_fin_real TIMESTAMP WITH TIME ZONE,
    ADD COLUMN motivo_cierre_anticipado VARCHAR(500);

COMMENT ON COLUMN solicitudes.fecha_inicio_real IS 'Entrega efectiva del vehiculo registrada por un administrador.';
COMMENT ON COLUMN solicitudes.fecha_fin_real IS 'Devolucion efectiva del vehiculo registrada por un administrador.';
COMMENT ON COLUMN solicitudes.motivo_cierre_anticipado IS 'Observacion obligatoria si la devolucion ocurre antes del fin previsto.';

CREATE TABLE pagos_reserva (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id BIGINT NOT NULL UNIQUE REFERENCES solicitudes(id) ON DELETE RESTRICT,
    metodo VARCHAR(24) NOT NULL,
    estado VARCHAR(24) NOT NULL DEFAULT 'PENDIENTE',
    referencia VARCHAR(120),
    observacion VARCHAR(500),
    revisado_por BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_pagos_metodo CHECK (metodo IN ('TRANSFERENCIA', 'EFECTIVO', 'TARJETA_PRESENCIAL')),
    CONSTRAINT chk_pagos_estado CHECK (estado IN (
        'PENDIENTE', 'REPORTADO', 'VERIFICADO', 'RECHAZADO',
        'REEMBOLSO_PENDIENTE', 'REEMBOLSADO'
    )),
    CONSTRAINT chk_pagos_referencia CHECK (referencia IS NULL OR LENGTH(TRIM(referencia)) >= 4)
);

CREATE INDEX idx_pagos_reserva_estado ON pagos_reserva(estado);
COMMENT ON TABLE pagos_reserva IS 'Declaraciones y verificaciones de pago EXTERNO; no es una pasarela de pagos.';
