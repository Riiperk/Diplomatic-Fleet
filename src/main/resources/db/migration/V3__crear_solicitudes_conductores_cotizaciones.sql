-- ============================================================
-- Diplomatic Fleet
-- Migración V3: solicitudes, conductores y cotizaciones
--
-- Esta migración crea las estructuras necesarias para:
-- 1. Registrar conductores autorizados por cada institución.
-- 2. Gestionar solicitudes de servicios vehiculares.
-- 3. Relacionar opcionalmente vehículos y conductores.
-- 4. Crear diferentes versiones de una cotización.
-- 5. Desglosar económicamente cada cotización.
--
-- El valor económico no se almacena en solicitudes porque una
-- solicitud puede recibir varias versiones de cotización.
-- ============================================================


-- ============================================================
-- TABLA: conductores_autorizados
-- ============================================================

CREATE TABLE conductores_autorizados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    cliente_institucional_id BIGINT NOT NULL,

    nombre_completo VARCHAR(140) NOT NULL,

    tipo_documento VARCHAR(30) NOT NULL,

    numero_documento VARCHAR(40) NOT NULL,

    numero_licencia VARCHAR(60) NOT NULL,

    categoria_licencia VARCHAR(20),

    fecha_vencimiento_licencia DATE NOT NULL,

    telefono VARCHAR(30),

    correo VARCHAR(150),

    activo BOOLEAN NOT NULL DEFAULT TRUE,

    creado_en TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    actualizado_en TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_conductores_cliente_institucional
        FOREIGN KEY (cliente_institucional_id)
        REFERENCES clientes_institucionales (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT chk_conductores_nombre_no_vacio
        CHECK (TRIM(nombre_completo) <> ''),

    CONSTRAINT chk_conductores_tipo_documento
        CHECK (
            tipo_documento IN (
                'CEDULA_CIUDADANIA',
                'CEDULA_EXTRANJERIA',
                'PASAPORTE',
                'OTRO'
            )
        ),

    CONSTRAINT chk_conductores_numero_documento_no_vacio
        CHECK (TRIM(numero_documento) <> ''),

    CONSTRAINT chk_conductores_numero_licencia_no_vacio
        CHECK (TRIM(numero_licencia) <> '')
);

CREATE UNIQUE INDEX uq_conductores_documento_normalizado
    ON conductores_autorizados (
        tipo_documento,
        UPPER(TRIM(numero_documento))
    );

CREATE UNIQUE INDEX uq_conductores_licencia_normalizada
    ON conductores_autorizados (
        UPPER(TRIM(numero_licencia))
    );

CREATE UNIQUE INDEX uq_conductores_correo_normalizado
    ON conductores_autorizados (
        LOWER(TRIM(correo))
    )
    WHERE correo IS NOT NULL;

COMMENT ON TABLE conductores_autorizados IS
    'Conductores que una entidad institucional autoriza para prestar o recibir servicios vehiculares.';

COMMENT ON COLUMN conductores_autorizados.cliente_institucional_id IS
    'Entidad institucional responsable de autorizar al conductor.';

COMMENT ON COLUMN conductores_autorizados.fecha_vencimiento_licencia IS
    'Fecha utilizada para verificar que la licencia esté vigente antes de asignar un servicio.';

COMMENT ON COLUMN conductores_autorizados.activo IS
    'Permite retirar una autorización sin eliminar el historial del conductor.';


-- ============================================================
-- TABLA: solicitudes
-- ============================================================

CREATE TABLE solicitudes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    codigo VARCHAR(30) NOT NULL,

    cliente_institucional_id BIGINT NOT NULL,

    usuario_creador_id BIGINT NOT NULL,

    vehiculo_id BIGINT,

    conductor_autorizado_id BIGINT,

    modalidad VARCHAR(30) NOT NULL,

    fecha_inicio TIMESTAMP WITH TIME ZONE NOT NULL,

    fecha_fin TIMESTAMP WITH TIME ZONE NOT NULL,

    lugar_recogida VARCHAR(255) NOT NULL,

    lugar_devolucion VARCHAR(255) NOT NULL,

    cantidad_pasajeros INTEGER NOT NULL,

    necesidades_especiales VARCHAR(1000),

    estado VARCHAR(30) NOT NULL DEFAULT 'RECIBIDA',

    motivo_cancelacion VARCHAR(500),

    creado_en TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    actualizado_en TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_solicitudes_codigo
        UNIQUE (codigo),

    CONSTRAINT fk_solicitudes_cliente_institucional
        FOREIGN KEY (cliente_institucional_id)
        REFERENCES clientes_institucionales (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_solicitudes_usuario_creador
        FOREIGN KEY (usuario_creador_id)
        REFERENCES usuarios (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_solicitudes_vehiculo
        FOREIGN KEY (vehiculo_id)
        REFERENCES vehiculos (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_solicitudes_conductor
        FOREIGN KEY (conductor_autorizado_id)
        REFERENCES conductores_autorizados (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT chk_solicitudes_codigo_no_vacio
        CHECK (TRIM(codigo) <> ''),

    CONSTRAINT chk_solicitudes_modalidad
        CHECK (
            modalidad IN (
                'CON_CONDUCTOR',
                'SIN_CONDUCTOR'
            )
        ),

    CONSTRAINT chk_solicitudes_orden_fechas
        CHECK (fecha_fin > fecha_inicio),

    CONSTRAINT chk_solicitudes_lugar_recogida_no_vacio
        CHECK (TRIM(lugar_recogida) <> ''),

    CONSTRAINT chk_solicitudes_lugar_devolucion_no_vacio
        CHECK (TRIM(lugar_devolucion) <> ''),

    CONSTRAINT chk_solicitudes_cantidad_pasajeros
        CHECK (cantidad_pasajeros BETWEEN 1 AND 100),

    CONSTRAINT chk_solicitudes_estado
        CHECK (
            estado IN (
                'RECIBIDA',
                'EN_REVISION',
                'COTIZADA',
                'PENDIENTE_APROBACION',
                'CONFIRMADA',
                'ASIGNADA',
                'EN_SERVICIO',
                'FINALIZADA',
                'RECHAZADA',
                'CANCELADA',
                'ARCHIVADA'
            )
        ),

    CONSTRAINT chk_solicitudes_cancelacion
        CHECK (
            estado <> 'CANCELADA'
            OR (
                motivo_cancelacion IS NOT NULL
                AND TRIM(motivo_cancelacion) <> ''
            )
        ),

    CONSTRAINT chk_solicitudes_conductor_modalidad
        CHECK (
            modalidad <> 'CON_CONDUCTOR'
            OR conductor_autorizado_id IS NOT NULL
        )
);

COMMENT ON TABLE solicitudes IS
    'Solicitudes institucionales de servicios vehiculares.';

COMMENT ON COLUMN solicitudes.codigo IS
    'Código legible y único utilizado para identificar la solicitud.';

COMMENT ON COLUMN solicitudes.vehiculo_id IS
    'Vehículo asignado. Puede quedar vacío mientras la solicitud está en revisión.';

COMMENT ON COLUMN solicitudes.conductor_autorizado_id IS
    'Conductor autorizado asignado cuando la modalidad requiere conductor.';

COMMENT ON COLUMN solicitudes.modalidad IS
    'Modalidad del servicio: CON_CONDUCTOR o SIN_CONDUCTOR.';

COMMENT ON COLUMN solicitudes.estado IS
    'Estado actual dentro del ciclo de vida institucional de la solicitud.';

COMMENT ON COLUMN solicitudes.motivo_cancelacion IS
    'Motivo obligatorio cuando la solicitud se encuentra CANCELADA.';


-- ============================================================
-- TABLA: cotizaciones
-- ============================================================

CREATE TABLE cotizaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    solicitud_id BIGINT NOT NULL,

    numero_version INTEGER NOT NULL,

    estado VARCHAR(30) NOT NULL DEFAULT 'BORRADOR',

    fecha_emision TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    valida_hasta DATE NOT NULL,

    subtotal NUMERIC(14, 2) NOT NULL DEFAULT 0,

    impuestos NUMERIC(14, 2) NOT NULL DEFAULT 0,

    descuentos NUMERIC(14, 2) NOT NULL DEFAULT 0,

    valor_total NUMERIC(14, 2) NOT NULL DEFAULT 0,

    observaciones VARCHAR(1000),

    creado_por_usuario_id BIGINT NOT NULL,

    creado_en TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    actualizado_en TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_cotizaciones_solicitud_version
        UNIQUE (solicitud_id, numero_version),

    CONSTRAINT fk_cotizaciones_solicitud
        FOREIGN KEY (solicitud_id)
        REFERENCES solicitudes (id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_cotizaciones_usuario_creador
        FOREIGN KEY (creado_por_usuario_id)
        REFERENCES usuarios (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT chk_cotizaciones_version
        CHECK (numero_version >= 1),

    CONSTRAINT chk_cotizaciones_estado
        CHECK (
            estado IN (
                'BORRADOR',
                'ENVIADA',
                'ACEPTADA',
                'RECHAZADA',
                'VENCIDA',
                'ANULADA'
            )
        ),

    CONSTRAINT chk_cotizaciones_subtotal
        CHECK (subtotal >= 0),

    CONSTRAINT chk_cotizaciones_impuestos
        CHECK (impuestos >= 0),

    CONSTRAINT chk_cotizaciones_descuentos
        CHECK (descuentos >= 0),

    CONSTRAINT chk_cotizaciones_total
        CHECK (valor_total >= 0),

    CONSTRAINT chk_cotizaciones_fechas
        CHECK (
            valida_hasta >= CAST(fecha_emision AS DATE)
        ),

    CONSTRAINT chk_cotizaciones_calculo_total
        CHECK (
            valor_total = subtotal + impuestos - descuentos
        )
);

COMMENT ON TABLE cotizaciones IS
    'Versiones económicas preparadas para una solicitud institucional.';

COMMENT ON COLUMN cotizaciones.numero_version IS
    'Número consecutivo de la cotización dentro de una misma solicitud.';

COMMENT ON COLUMN cotizaciones.valida_hasta IS
    'Fecha límite hasta la cual la cotización puede ser aceptada.';

COMMENT ON COLUMN cotizaciones.subtotal IS
    'Suma de los detalles antes de impuestos y descuentos.';

COMMENT ON COLUMN cotizaciones.valor_total IS
    'Resultado de subtotal más impuestos menos descuentos.';


-- ============================================================
-- TABLA: detalles_cotizacion
-- ============================================================

CREATE TABLE detalles_cotizacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    cotizacion_id BIGINT NOT NULL,

    concepto VARCHAR(150) NOT NULL,

    descripcion VARCHAR(500),

    cantidad NUMERIC(10, 2) NOT NULL,

    valor_unitario NUMERIC(14, 2) NOT NULL,

    subtotal NUMERIC(14, 2)
        GENERATED ALWAYS AS (
            ROUND(cantidad * valor_unitario, 2)
        ) STORED,

    orden INTEGER NOT NULL DEFAULT 1,

    creado_en TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_detalles_cotizacion
        FOREIGN KEY (cotizacion_id)
        REFERENCES cotizaciones (id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT chk_detalles_concepto_no_vacio
        CHECK (TRIM(concepto) <> ''),

    CONSTRAINT chk_detalles_cantidad
        CHECK (cantidad > 0),

    CONSTRAINT chk_detalles_valor_unitario
        CHECK (valor_unitario >= 0),

    CONSTRAINT chk_detalles_orden
        CHECK (orden >= 1)
);

COMMENT ON TABLE detalles_cotizacion IS
    'Conceptos económicos que componen una cotización.';

COMMENT ON COLUMN detalles_cotizacion.cantidad IS
    'Cantidad de unidades, días, kilómetros u otro valor asociado al concepto.';

COMMENT ON COLUMN detalles_cotizacion.valor_unitario IS
    'Valor monetario por cada unidad del concepto.';

COMMENT ON COLUMN detalles_cotizacion.subtotal IS
    'Valor calculado automáticamente como cantidad multiplicada por valor unitario.';

COMMENT ON COLUMN detalles_cotizacion.orden IS
    'Posición usada para presentar ordenadamente los conceptos de la cotización.';


