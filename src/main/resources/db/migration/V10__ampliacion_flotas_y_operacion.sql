-- Historial técnico de mutaciones a partir de V10; no copia contraseñas, contactos,
-- números de documentos ni datos bancarios. El usuario BD no equivale al actor web.
CREATE TABLE auditoria_operativa (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tabla VARCHAR(80) NOT NULL,
 registro_id BIGINT NOT NULL,
 operacion VARCHAR(10) NOT NULL CHECK(operacion IN ('INSERT','UPDATE','DELETE')),
 estado_anterior TEXT,
 estado_nuevo TEXT,
 fecha TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 usuario_bd TEXT NOT NULL
);
CREATE INDEX idx_auditoria_fecha ON auditoria_operativa(fecha DESC,id DESC);
COMMENT ON TABLE auditoria_operativa IS 'Historial técnico desde V10. No es una auditoría de identidad web ni se reconstruyen eventos anteriores.';
-- Se extrae exclusivamente la identidad numérica y el estado/activo del registro.
CREATE FUNCTION df_auditar_operacion() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE anterior jsonb; nuevo jsonb; identificador bigint;
BEGIN
 IF TG_OP <> 'INSERT' THEN anterior := to_jsonb(OLD); END IF;
 IF TG_OP <> 'DELETE' THEN nuevo := to_jsonb(NEW); END IF;
 identificador := COALESCE((nuevo->>'id')::bigint,(anterior->>'id')::bigint);
 INSERT INTO auditoria_operativa(tabla,registro_id,operacion,estado_anterior,estado_nuevo,usuario_bd)
 VALUES(TG_TABLE_NAME,identificador,TG_OP,COALESCE(anterior->>'estado',anterior->>'activo'),COALESCE(nuevo->>'estado',nuevo->>'activo'),current_user);
 IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
 RETURN NEW;
END;
$$;
-- La misma función conserva la trazabilidad básica de cada módulo operativo.
DO $$ DECLARE t text;
BEGIN
 FOREACH t IN ARRAY ARRAY['solicitudes','pagos_reserva','cotizaciones','vehiculos','clientes_institucionales','mantenimientos','documentos_vehiculo','conductores_autorizados','conductores_profesionales','usuarios']
 LOOP
  EXECUTE format('CREATE TRIGGER df_auditoria AFTER INSERT OR UPDATE OR DELETE ON %I FOR EACH ROW EXECUTE FUNCTION df_auditar_operacion()',t);
 END LOOP;
END; $$;
