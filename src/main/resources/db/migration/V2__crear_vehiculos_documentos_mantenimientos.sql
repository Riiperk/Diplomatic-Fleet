-- ============================================================
-- Diplomatic Fleet
-- Migración V2: vehículos, documentos y mantenimientos
--
-- Esta migración crea las estructuras utilizadas para:
-- 1. Clasificar la flota institucional.
-- 2. Registrar los vehículos y su estado operativo.
-- 3. Controlar la vigencia de documentos vehiculares.
-- 4. Registrar mantenimientos preventivos y correctivos.
--
-- La disponibilidad no se almacena como un valor booleano.
-- Se determina mediante el estado del vehículo, las solicitudes
-- asignadas y los mantenimientos activos.
-- ============================================================


-- ============================================================
-- TABLA: categorias_vehiculo
-- ============================================================

CREATE TABLE categorias_vehiculo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    codigo VARCHAR(30) NOT NULL,

    nombre VARCHAR(70) NOT NULL,

    descripcion VARCHAR(255),

    activo BOOLEAN NOT NULL DEFAULT TRUE,

    creado_en TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_categorias_vehiculo_codigo
        UNIQUE (codigo),

    CONSTRAINT chk_categorias_vehiculo_codigo
        CHECK (
            codigo IN (
                'ECONOMICO',
                'EJECUTIVO',
                'PREMIUM'
            )
        ),

    CONSTRAINT chk_categorias_vehiculo_nombre_no_vacio
        CHECK (TRIM(nombre) <> '')
);

COMMENT ON TABLE categorias_vehiculo IS
    'Clasificación de vehículos de acuerdo con el nivel de servicio ofrecido.';

COMMENT ON COLUMN categorias_vehiculo.codigo IS
    'Código estable utilizado por el backend: ECONOMICO, EJECUTIVO o PREMIUM.';

COMMENT ON COLUMN categorias_vehiculo.nombre IS
    'Nombre visible de la categoría.';

COMMENT ON COLUMN categorias_vehiculo.activo IS
    'Indica si la categoría puede asignarse a nuevos vehículos.';


-- ============================================================
-- TABLA: vehiculos
-- ============================================================

CREATE TABLE vehiculos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    categoria_id BIGINT NOT NULL,

    placa VARCHAR(12) NOT NULL,

    marca VARCHAR(60) NOT NULL,

    modelo VARCHAR(60) NOT NULL,

    anio INTEGER NOT NULL,

    color VARCHAR(40) NOT NULL,

    combustible VARCHAR(30) NOT NULL,

    capacidad_pasajeros INTEGER NOT NULL,

    capacidad_equipaje INTEGER NOT NULL DEFAULT 0,

    estado VARCHAR(30) NOT NULL DEFAULT 'DISPONIBLE',

    activo BOOLEAN NOT NULL DEFAULT TRUE,

    creado_en TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    actualizado_en TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_vehiculos_categoria
        FOREIGN KEY (categoria_id)
        REFERENCES categorias_vehiculo (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT chk_vehiculos_placa_no_vacia
        CHECK (TRIM(placa) <> ''),

    CONSTRAINT chk_vehiculos_marca_no_vacia
        CHECK (TRIM(marca) <> ''),

    CONSTRAINT chk_vehiculos_modelo_no_vacio
        CHECK (TRIM(modelo) <> ''),

    CONSTRAINT chk_vehiculos_anio
        CHECK (anio BETWEEN 1950 AND 2100),

    CONSTRAINT chk_vehiculos_capacidad_pasajeros
        CHECK (capacidad_pasajeros BETWEEN 1 AND 100),

    CONSTRAINT chk_vehiculos_capacidad_equipaje
        CHECK (capacidad_equipaje >= 0),

    CONSTRAINT chk_vehiculos_combustible
        CHECK (
            combustible IN (
                'GASOLINA',
                'DIESEL',
                'HIBRIDO',
                'ELECTRICO'
            )
        ),

    CONSTRAINT chk_vehiculos_estado
        CHECK (
            estado IN (
                'DISPONIBLE',
                'RESERVADO',
                'EN_SERVICIO',
                'EN_MANTENIMIENTO',
                'INACTIVO'
            )
        )
);

-- Una placa no puede repetirse aunque se escriba con otra combinación
-- de mayúsculas, minúsculas o espacios.
CREATE UNIQUE INDEX uq_vehiculos_placa_normalizada
    ON vehiculos (
        UPPER(TRIM(placa))
    );

COMMENT ON TABLE vehiculos IS
    'Vehículos que conforman la flota administrada por Diplomatic Fleet.';

COMMENT ON COLUMN vehiculos.categoria_id IS
    'Categoría de servicio asignada al vehículo.';

COMMENT ON COLUMN vehiculos.placa IS
    'Identificador único del vehículo, normalizado por la aplicación.';

COMMENT ON COLUMN vehiculos.capacidad_pasajeros IS
    'Cantidad máxima de pasajeros permitida, sin incluir valores negativos o cero.';

COMMENT ON COLUMN vehiculos.capacidad_equipaje IS
    'Capacidad de equipaje expresada como cantidad estimada de piezas.';

COMMENT ON COLUMN vehiculos.estado IS
    'Estado operativo: DISPONIBLE, RESERVADO, EN_SERVICIO, EN_MANTENIMIENTO o INACTIVO.';

COMMENT ON COLUMN vehiculos.activo IS
    'Permite retirar un vehículo de la operación sin borrar su historial.';


-- ============================================================
-- TABLA: documentos_vehiculo
-- ============================================================

CREATE TABLE documentos_vehiculo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    vehiculo_id BIGINT NOT NULL,

    tipo_documento VARCHAR(40) NOT NULL,

    numero_documento VARCHAR(80),

    fecha_emision DATE,

    fecha_vencimiento DATE NOT NULL,

    estado VARCHAR(20) NOT NULL DEFAULT 'VIGENTE',

    observaciones VARCHAR(500),

    creado_en TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    actualizado_en TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_documentos_vehiculo
        FOREIGN KEY (vehiculo_id)
        REFERENCES vehiculos (id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT chk_documentos_vehiculo_tipo
        CHECK (
            tipo_documento IN (
                'SOAT',
                'REVISION_TECNOMECANICA',
                'TARJETA_PROPIEDAD',
                'POLIZA',
                'OTRO'
            )
        ),

    CONSTRAINT chk_documentos_vehiculo_estado
        CHECK (
            estado IN (
                'VIGENTE',
                'PROXIMO_A_VENCER',
                'VENCIDO'
            )
        ),

    CONSTRAINT chk_documentos_vehiculo_fechas
        CHECK (
            fecha_emision IS NULL
            OR fecha_vencimiento >= fecha_emision
        )
);

-- Un vehículo no debe tener dos registros activos del mismo tipo
-- y con la misma fecha de vencimiento.
CREATE UNIQUE INDEX uq_documentos_vehiculo_tipo_vencimiento
    ON documentos_vehiculo (
        vehiculo_id,
        tipo_documento,
        fecha_vencimiento
    );

COMMENT ON TABLE documentos_vehiculo IS
    'Documentos y vencimientos asociados a los vehículos de la flota.';

COMMENT ON COLUMN documentos_vehiculo.tipo_documento IS
    'Tipo documental controlado por el sistema.';

COMMENT ON COLUMN documentos_vehiculo.fecha_vencimiento IS
    'Fecha utilizada para determinar la vigencia del documento.';

COMMENT ON COLUMN documentos_vehiculo.estado IS
    'Estado calculado o actualizado según la fecha de vencimiento.';


-- ============================================================
-- TABLA: mantenimientos
-- ============================================================

CREATE TABLE mantenimientos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    vehiculo_id BIGINT NOT NULL,

    tipo VARCHAR(20) NOT NULL,

    estado VARCHAR(20) NOT NULL DEFAULT 'PROGRAMADO',

    descripcion VARCHAR(500) NOT NULL,

    fecha_programada DATE NOT NULL,

    fecha_inicio TIMESTAMP WITH TIME ZONE,

    fecha_fin TIMESTAMP WITH TIME ZONE,

    costo NUMERIC(12, 2),

    proveedor VARCHAR(150),

    observaciones VARCHAR(500),

    creado_en TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    actualizado_en TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_mantenimientos_vehiculo
        FOREIGN KEY (vehiculo_id)
        REFERENCES vehiculos (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT chk_mantenimientos_tipo
        CHECK (
            tipo IN (
                'PREVENTIVO',
                'CORRECTIVO'
            )
        ),

    CONSTRAINT chk_mantenimientos_estado
        CHECK (
            estado IN (
                'PROGRAMADO',
                'EN_PROCESO',
                'FINALIZADO',
                'CANCELADO'
            )
        ),

    CONSTRAINT chk_mantenimientos_descripcion_no_vacia
        CHECK (TRIM(descripcion) <> ''),

    CONSTRAINT chk_mantenimientos_costo
        CHECK (
            costo IS NULL
            OR costo >= 0
        ),

    CONSTRAINT chk_mantenimientos_fechas
        CHECK (
            fecha_fin IS NULL
            OR fecha_inicio IS NOT NULL
        ),

    CONSTRAINT chk_mantenimientos_orden_fechas
        CHECK (
            fecha_fin IS NULL
            OR fecha_fin >= fecha_inicio
        )
);

COMMENT ON TABLE mantenimientos IS
    'Historial de mantenimientos preventivos y correctivos realizados a los vehículos.';

COMMENT ON COLUMN mantenimientos.tipo IS
    'Tipo de mantenimiento: PREVENTIVO o CORRECTIVO.';

COMMENT ON COLUMN mantenimientos.estado IS
    'Estado del proceso: PROGRAMADO, EN_PROCESO, FINALIZADO o CANCELADO.';

COMMENT ON COLUMN mantenimientos.costo IS
    'Costo del mantenimiento. Debe ser mayor o igual que cero.';

COMMENT ON COLUMN mantenimientos.fecha_inicio IS
    'Fecha y hora en que comenzó efectivamente el mantenimiento.';

COMMENT ON COLUMN mantenimientos.fecha_fin IS
    'Fecha y hora en que finalizó el mantenimiento.';


